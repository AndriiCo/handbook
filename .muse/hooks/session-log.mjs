// Session log: the prompt-and-response record, written from Muse's own
// session log instead of by the agent. One Markdown file per session in
// docs/prompts/sessions/ (builder, judge, any other session in this repo):
// every turn, what started it (you, the goal, subagent results, a message
// from another session, a background task), the prompt, the final answer,
// your answers to its questions, and the commits made during the turn.
// Tool calls, tool output and reasoning are left out; the export is
// --redacted. Raw logs stay in Muse's store: `muse export --session <id>`.
//
//   node .muse/hooks/session-log.mjs                    # every session in this repo since --since
//   node .muse/hooks/session-log.mjs --session <uuid>
//   node .muse/hooks/session-log.mjs --export <file>    # an existing `muse export` file
//   run.sh session-log --hook                           # Stop hook: the current session
import { execFileSync, spawn } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readInput } from './lib.mjs';

const args = parseArgs(process.argv.slice(2));
const SINCE = Date.parse(args.since || '2026-10-30T02:00:00Z'); // 001-095 are the per-prompt files
const CAP = { prompt: 1500, answer: 6000, message: 1500, title: 160 };
const GOAL_STEP = 'Continue working toward the active session goal';

const mainRoot = gitMainRoot();
const outDir = join(mainRoot, 'docs/prompts/sessions');
// Sessions belong to this repo when their workspace is the main checkout or
// a worktree inside it (subagents, the judge's `muse -w`).
const workspaceRoot = realpath(args.workspace || mainRoot);
const index = openIndex();

let targets;
if (args.hook) {
  // Stop hook: hand the work to a detached copy and return at once, so a
  // large session never delays the end of a turn.
  const input = readInput();
  const id = input.session_id || process.env.MUSE_SESSION_ID;
  const prev = existingFile(id);
  if (!id || (prev && Date.now() - statSync(prev).mtimeMs < 60_000)) process.exit(0); // goal sessions end turns often
  spawn(process.execPath, ['--no-warnings', fileURLToPath(import.meta.url), '--session', id, '--from-hook'], { cwd: mainRoot, detached: true, stdio: 'ignore' }).unref();
  process.exit(0);
} else if (args.export) {
  targets = [{ id: null, file: args.export }];
} else if (args.session) {
  targets = [{ id: String(args.session) }];
} else {
  targets = repoSessions();
}

mkdirSync(outDir, { recursive: true });
for (const t of targets) {
  try {
    writeDigest(t);
  } catch (err) {
    console.error(`session-log: ${t.id ?? t.file}: ${String(err?.message || err).slice(0, 200)}`);
  }
}
writeIndex();

// ------------------------------------------------------------------ digest

function writeDigest(target) {
  const meta = target.id ? sessionMeta(target.id) : {};
  if (args['from-hook'] && meta.created && meta.created < SINCE) return;
  const exportFile = target.file || exportSession(target.id);
  const doc = JSON.parse(readFileSync(exportFile, 'utf8'));
  if (!target.file) unlinkSync(exportFile);

  const sessionId = doc.sessions?.[0]?.session_id ?? target.id;
  const runs = collectRuns(doc.events ?? []);
  if (!runs.length) return;
  attachCommits(runs);

  const name = slug(meta.name || 'session');
  const start = runs[0].start;
  const end = Math.max(...runs.map((r) => r.end));
  const counts = countBy(runs.map((r) => r.kind));
  const commits = runs.reduce((n, r) => n + r.commits.length, 0);
  const where = meta.workspace ? relative(workspaceRoot, realpath(meta.workspace)) || 'main checkout' : 'unknown';

  const out = [];
  out.push(`# ${meta.name || 'Session'} · Muse Code session ${sessionId.slice(0, 8)}`);
  out.push('');
  out.push(`<!-- session-log: ${JSON.stringify({ id: sessionId, name: meta.name ?? null, start: iso(start), end: iso(end), runs: runs.length, ...counts, commits })} -->`);
  out.push(`- ${iso(start)} → ${iso(end)} UTC · ${runs.length} turns (${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')}) · ${commits} commits`);
  out.push(`- Workspace: ${where} · model ${meta.model ?? '?'}`);
  out.push(`- Generated by \`.muse/hooks/session-log.mjs\` from Muse's redacted session log. Tool calls, tool output and reasoning are left out. Full log: \`muse export --session ${sessionId} --redacted\`.`);
  for (const [i, r] of runs.entries()) {
    out.push('', `## ${i + 1}. ${iso(r.start)} UTC · ${r.label} · ${duration(r.ms)}${r.terminal && r.terminal !== 'completed' ? ` · ${r.terminal}` : ''}`);
    if (r.goalText) out.push('', `**Goal (${r.goalAction} by you)**`, '', quote(cap(unescapeXml(r.goalText), CAP.prompt)));
    if (r.kind === 'you' && r.prompt) out.push('', '**Prompt**', '', quote(cap(r.prompt, CAP.prompt)));
    if (r.kind === 'other' && r.prompt) out.push('', '**Prompt (not typed in this session)**', '', quote(cap(r.prompt, CAP.prompt)));
    for (const m of r.messages) out.push('', `**Message from ${m.from}**`, '', quote(cap(m.text, CAP.message)));
    for (const a of r.answers) out.push('', `**You answered:** ${a}`);
    if (r.subagents.length) out.push('', `**Subagent results (${r.subagents.length})**`, '', ...r.subagents.map((s) => `- ${cap(s, CAP.title)}`));
    if (r.answer) out.push('', '**Response**', '', demoteHeadings(cap(r.answer, CAP.answer)));
    if (r.commits.length) out.push('', '**Commits**', '', ...r.commits.map((c) => `- \`${c.hash}\` ${c.subject}`));
  }
  const file = join(outDir, `${iso(start).slice(0, 10)}-${name}-${sessionId.slice(0, 8)}.md`);
  const stale = existingFile(sessionId);
  if (stale && stale !== file) unlinkSync(stale);
  writeFileSync(file, out.join('\n') + '\n');
}

function collectRuns(events) {
  const runs = new Map();
  const intents = new Set();
  const run = (id, at) => {
    if (!runs.has(id)) runs.set(id, { id, start: at, end: at, prompt: '', finals: [], commentary: [], inbox: [], answers: [], terminal: null, ms: 0 });
    return runs.get(id);
  };
  for (const e of events) {
    if (e.kind !== 'record') continue;
    const env = e.envelope ?? {};
    const p = env.payload ?? {};
    const at = Math.round((env.recorded_at ?? e.recorded_at ?? 0) / 1000);
    if (env.payload_type === 'runtime.user_intent.accepted' && p.intent_id) intents.add(p.intent_id);
    if (p.kind !== 'run' || !p.run_id) continue;
    const r = run(p.run_id, at);
    r.end = Math.max(r.end, at);
    const ev = p.event ?? {};
    switch (ev.kind) {
      case 'started': r.prompt = ev.prompt ?? ''; r.start = Math.min(r.start, at); break;
      case 'assistant_message_committed':
        (ev.phase === 'commentary' ? r.commentary : r.finals).push(ev.text ?? '');
        break;
      case 'inbox_item_queued':
        r.inbox.push({
          source: ev.source?.source ?? 'unknown',
          summary: ev.summary ?? '',
          // `body` is cut at ~1200 characters; the model's copy is whole.
          text: (ev.payload?.model_user_messages ?? []).join('\n') || ev.body || ev.summary || '',
          raw: ev.source ?? {},
        });
        break;
      case 'user_input_prompt_settled':
        if (ev.outcome === 'answered') for (const a of ev.answers ?? []) r.answers.push((a.selected_labels ?? []).concat(a.text ?? a.note ?? []).join('; ') || '(free text)');
        else r.answers.push(`(${ev.outcome})`);
        break;
      case 'terminal': r.terminal = ev.terminal; r.ms = ev.turn_duration_ms ?? r.end - r.start; break;
      default:
    }
  }
  const list = [...runs.values()].sort((a, b) => a.start - b.start);
  for (const r of list) {
    if (!r.ms) r.ms = r.end - r.start;
    r.answer = r.finals.filter((t) => t.trim()).at(-1) ?? r.commentary.filter((t) => t.trim()).at(-1) ?? '';
    r.subagents = r.inbox.filter((i) => i.source === 'subagent_result').map((i) => firstLine(i.summary));
    r.messages = r.inbox.filter((i) => /message|peer/i.test(i.source)).map((i) => ({ from: peerName(i.raw), text: i.text }));
    // `/goal <objective>` typed by the operator arrives as a goal_control item, not a prompt.
    const control = r.inbox.find((i) => i.source === 'goal_control' && /changed by user request/.test(i.text));
    if (control) {
      r.goalAction = control.text.match(/action="([a-z_]+)"/)?.[1] ?? 'change';
      r.goalText = control.text.match(/<objective>([\s\S]*?)<\/objective>/)?.[1]?.trim() ?? '';
    }
    const prompt = r.prompt.trim();
    if (control) [r.kind, r.label] = ['you', `you: /goal ${r.goalAction}`];
    else if (prompt.startsWith(GOAL_STEP)) [r.kind, r.label] = ['goal', 'goal: continue'];
    else if (prompt && (intents.has(r.id) || prompt.startsWith('/'))) [r.kind, r.label] = ['you', 'you'];
    else if (prompt) [r.kind, r.label] = ['other', 'scheduled or system prompt'];
    else {
      const sources = [...new Set(r.inbox.map((i) => i.source))];
      r.kind = r.messages.length ? 'message' : sources.some((s) => /goal/.test(s)) ? 'goal' : 'auto';
      r.label = sources.length ? `woken by ${sources.map(describeSource).join(', ')}` : 'automatic';
    }
  }
  return list;
}

// Commits made while a turn ran, in this repo or a subagent's worktree branch.
function attachCommits(runs) {
  const seen = new Set();
  for (const r of runs) {
    r.commits = [];
    let log = '';
    try {
      log = execFileSync('git', ['-C', mainRoot, 'log', '--all', `--since=${iso(r.start)}Z`, `--until=${iso(r.start + r.ms + 5000)}Z`, '--format=%h%x09%s'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    } catch {
      continue;
    }
    for (const line of log.trim().split('\n').filter(Boolean).reverse()) {
      const [hash, subject] = line.split('\t');
      if (seen.has(hash)) continue;
      seen.add(hash);
      r.commits.push({ hash, subject });
    }
  }
}

// ------------------------------------------------------------------- index

function writeIndex() {
  const rows = readdirSync(outDir)
    .filter((f) => /^\d{4}-\d\d-\d\d-.+\.md$/.test(f))
    .sort()
    .map((f) => {
      const m = readFileSync(join(outDir, f), 'utf8').match(/<!-- session-log: (\{.*\}) -->/);
      return m ? { f, ...JSON.parse(m[1]) } : null;
    })
    .filter(Boolean);
  const total = (k) => rows.reduce((n, r) => n + (r[k] ?? 0), 0);
  const out = [
    '# Muse Code sessions from 2026-10-30',
    '',
    'Prompts 001-095 are the per-prompt files in `docs/prompts/`. From then on, every Muse session in this repo has one file here, written by `.muse/hooks/session-log.mjs` from Muse\'s own session log: the builder session, the judge session and any other.',
    '',
    `${rows.length} sessions, ${total('runs')} turns (${total('you')} typed by the operator, ${total('goal')} driven by the goal), ${total('commits')} commits.`,
    '',
    '| Session | Start (UTC) | End (UTC) | Turns | Operator | Goal | Other | Commits |',
    '|---|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| [${r.name ?? 'session'} ${r.id.slice(0, 8)}](${r.f}) | ${r.start} | ${r.end} | ${r.runs} | ${r.you ?? 0} | ${r.goal ?? 0} | ${r.runs - (r.you ?? 0) - (r.goal ?? 0)} | ${r.commits} |`),
  ];
  writeFileSync(join(outDir, 'README.md'), out.join('\n') + '\n');
}

// ----------------------------------------------------------- muse plumbing

function exportSession(id) {
  const file = join(tmpdir(), `session-log-${id}-${process.pid}.json`);
  execFileSync('muse', ['export', '--session', id, '--redacted', '--out', file], { stdio: ['ignore', 'ignore', 'pipe'], timeout: 120_000 });
  return file;
}

// Muse's session index (SQLite, read-only). Absent or unreadable: names and
// workspaces are unknown, and --all finds nothing.
function openIndex() {
  try {
    const { DatabaseSync } = process.getBuiltinModule('node:sqlite');
    const path = join(homedir(), '.local/share/muse/session-index.db');
    return existsSync(path) ? new DatabaseSync(path, { readOnly: true }) : null;
  } catch {
    return null;
  }
}

function sessionMeta(id) {
  const row = index?.prepare('select session_name, workspace_root, created_at_us, model_id from sessions where session_id = ?').get(id);
  return row ? { name: row.session_name, workspace: row.workspace_root, created: row.created_at_us / 1000, model: row.model_id } : {};
}

function repoSessions() {
  if (!index) return [];
  return index
    .prepare("select session_id, workspace_root from sessions where created_at_us >= ? and coalesce(msp_kind, 'root') = 'root' order by created_at_us")
    .all(SINCE * 1000)
    .filter((r) => r.workspace_root && (realpath(r.workspace_root) + '/').startsWith(workspaceRoot + '/'))
    .map((r) => ({ id: r.session_id }));
}

// --------------------------------------------------------------- helpers

function gitMainRoot() {
  const common = execFileSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], { encoding: 'utf8' }).trim();
  return dirname(common);
}

function existingFile(id) {
  if (!id || !existsSync(outDir)) return null;
  const f = readdirSync(outDir).find((n) => n.endsWith(`-${id.slice(0, 8)}.md`));
  return f ? join(outDir, f) : null;
}

function describeSource(s) {
  return {
    subagent_result: 'subagent results',
    subagent_input: 'a subagent question',
    goal_progress_nudge: 'the goal',
    goal_control: 'a goal change',
    background_task_terminal: 'a finished background task',
    background_task_overdue: 'an overdue background task',
  }[s] ?? s.replace(/_/g, ' ');
}

function peerName(src) {
  return src.sender_name || src.from_session_name || src.sender?.name || src.sender_session_id?.slice(0, 8) || 'another session';
}

function realpath(p) {
  try {
    return realpathSync(p);
  } catch {
    return p;
  }
}

function countBy(xs) {
  const out = {};
  for (const x of xs) out[x] = (out[x] ?? 0) + 1;
  return out;
}

function iso(ms) {
  return new Date(ms).toISOString().slice(0, 16).replace('T', ' ');
}

function duration(ms) {
  const s = Math.round(ms / 1000);
  return s < 60 ? `${s}s` : s < 3600 ? `${Math.floor(s / 60)}m ${s % 60}s` : `${Math.floor(s / 3600)}h ${Math.floor((s % 3600) / 60)}m`;
}

function cap(s, n) {
  const t = String(s).trim();
  return t.length <= n ? t : `${t.slice(0, n)}\n\n… (${t.length - n} more characters in the session log)`;
}

function quote(s) {
  return s.split('\n').map((l) => `> ${l}`).join('\n');
}

// A response's own "## Steps" must not read as the next turn.
function demoteHeadings(s) {
  let fenced = false;
  return s.split('\n').map((l) => {
    if (/^\s*(```|~~~)/.test(l)) fenced = !fenced;
    return fenced ? l : l.replace(/^#{1,3}(?=\s)/, '####');
  }).join('\n');
}

function unescapeXml(s) {
  return s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&');
}

function firstLine(s) {
  return String(s).split('\n').map((l) => l.replace(/^#+\s*/, '').trim()).find(Boolean) ?? '';
}

function slug(s) {
  return String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'session';
}

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i += 1) {
    const m = argv[i].match(/^--([a-z-]+)(?:=(.*))?$/);
    if (!m) continue;
    out[m[1]] = m[2] ?? (argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true);
  }
  return out;
}

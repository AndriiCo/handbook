//! Per-form project scaffold + generated-copy compare.
//!
//! `cargo xtask form-scaffold --authority <slug> --code <code>
//! --title <title> [--out <dir>] [--force]` creates the §3 skeleton
//! (`forms/<authority>/<code>/REQUIREMENTS.md` + `v1.json`) and the
//! generated web copy, per `docs/specs/form-framework.md` §4.
//!
//! `cargo xtask form-scaffold --check --authority <slug> --code
//! <code> [--out <dir>]` fails when the generated copy drifts from
//! the latest `v<n>.json`.

use std::path::{Path, PathBuf};

/// Scaffold a per-form project. Returns every file written.
/// Creates parent dirs; refuses to overwrite without `force`.
pub fn scaffold(
    out: &Path,
    authority: &str,
    code: &str,
    title: &str,
    force: bool,
) -> Result<Vec<PathBuf>, String> {
    validate_slug(authority, "authority")?;
    validate_slug(code, "code")?;
    if title.trim().is_empty() {
        return Err("title must not be blank".to_string());
    }
    let dir = out.join("forms").join(authority).join(code);
    let requirements = dir.join("REQUIREMENTS.md");
    let v1 = dir.join("v1.json");
    let generated = generated_path(out, authority, code);
    if !force {
        for path in [&requirements, &v1, &generated] {
            if path.exists() {
                return Err(format!(
                    "{} exists (pass --force to overwrite)",
                    path.display()
                ));
            }
        }
    }
    let template = minimal_template(authority, code, title);
    write_file(&requirements, requirements_md(authority, code, title))?;
    write_file(&v1, format!("{template}\n"))?;
    write_file(&generated, format!("{template}\n"))?;
    Ok(vec![requirements, v1, generated])
}

/// Byte-compare the latest `v<n>.json` against the generated web
/// copy. Ok when identical; Err with a key-level diff otherwise.
pub fn check(out: &Path, authority: &str, code: &str) -> Result<(), String> {
    validate_slug(authority, "authority")?;
    validate_slug(code, "code")?;
    let dir = out.join("forms").join(authority).join(code);
    let Some((version, source)) = latest_version(&dir) else {
        return Err(format!("no v<n>.json under {}", dir.display()));
    };
    let generated = generated_path(out, authority, code);
    let want = std::fs::read(&source).map_err(|e| format!("read {}: {e}", source.display()))?;
    let got =
        std::fs::read(&generated).map_err(|e| format!("read {}: {e}", generated.display()))?;
    if want == got {
        return Ok(());
    }
    Err(format!(
        "generated copy drifts from v{version}: {}",
        summarize_diff(&want, &got)
    ))
}

/// Highest `v<n>.json` in `dir`, or None when there is no edition.
fn latest_version(dir: &Path) -> Option<(u32, PathBuf)> {
    let entries = std::fs::read_dir(dir).ok()?;
    let mut best: Option<(u32, PathBuf)> = None;
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let Some(num) = name.strip_prefix('v').and_then(|s| s.strip_suffix(".json")) else {
            continue;
        };
        let Ok(n) = num.parse::<u32>() else { continue };
        if n == 0 {
            continue;
        }
        if best.as_ref().is_none_or(|(top, _)| n > *top) {
            best = Some((n, entry.path()));
        }
    }
    best
}

/// Compare two template JSON blobs for the drift message: field-key
/// sets first (the usual edit), else top-level keys, else raw bytes.
fn summarize_diff(want: &[u8], got: &[u8]) -> String {
    let source_keys = field_keys(want);
    let generated_keys = field_keys(got);
    match (source_keys, generated_keys) {
        (Some(source), Some(generated)) if source != generated => {
            let added: Vec<_> = generated.difference(&source).collect();
            let removed: Vec<_> = source.difference(&generated).collect();
            format!("field keys added={added:?} removed={removed:?}")
        }
        _ => {
            let top = |bytes: &[u8]| -> Option<std::collections::BTreeSet<String>> {
                let value: serde_json::Value = serde_json::from_slice(bytes).ok()?;
                Some(value.as_object()?.keys().cloned().collect())
            };
            match (top(want), top(got)) {
                (Some(a), Some(b)) if a != b => {
                    let added: Vec<_> = b.difference(&a).collect();
                    let removed: Vec<_> = a.difference(&b).collect();
                    format!("top-level keys added={added:?} removed={removed:?}")
                }
                _ => format!(
                    "{} source bytes vs {} generated bytes",
                    want.len(),
                    got.len()
                ),
            }
        }
    }
}

/// Sorted `fields[].key` set of a template blob, or None when the
/// blob is not template-shaped JSON.
fn field_keys(bytes: &[u8]) -> Option<std::collections::BTreeSet<String>> {
    let value: serde_json::Value = serde_json::from_slice(bytes).ok()?;
    let fields = value.get("fields")?.as_array()?;
    fields
        .iter()
        .map(|f| f.get("key")?.as_str().map(str::to_string))
        .collect()
}

/// Slugs/codes are `[a-z0-9-]`, non-empty, with at least one
/// alphanumeric (so the `__` generated-copy join stays unambiguous).
fn validate_slug(value: &str, what: &str) -> Result<(), String> {
    let ok = !value.is_empty()
        && value
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
        && value.chars().any(|c| c.is_ascii_alphanumeric());
    if ok {
        Ok(())
    } else {
        Err(format!("{what} {value:?} must match [a-z0-9-]+"))
    }
}

/// Generated web copy bundled into the release (static import).
fn generated_path(out: &Path, authority: &str, code: &str) -> PathBuf {
    out.join("web")
        .join("src")
        .join("lib")
        .join("forms")
        .join("generated")
        .join(format!("{authority}__{code}.json"))
}

/// Write `content`, creating parent dirs. Fails closed on any IO error.
fn write_file(path: &Path, content: String) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("create {}: {e}", parent.display()))?;
    }
    std::fs::write(path, content).map_err(|e| format!("write {}: {e}", path.display()))
}

/// Minimal valid `FormTemplate` JSON: draft, version 1, no fields.
fn minimal_template(authority: &str, code: &str, title: &str) -> String {
    serde_json::json!({
        "authority": authority,
        "code": code,
        "title": title,
        "version": 1,
        "authority_revision": "TBD",
        "status": "draft",
        "fields": [],
        "accepts_replica": "unknown",
        "accepts_drawn_signature": false,
        "signature_mode": "wet_ink",
        "verify_cadence_days": 90,
        "created_by": "form-scaffold",
        "created_at": 0,
    })
    .to_string()
}

/// `REQUIREMENTS.md` starter with the verification-status table.
fn requirements_md(authority: &str, code: &str, title: &str) -> String {
    format!(
        "# {title} ({authority} / {code})\n\
         \n\
         Per-form project (form-framework.md §3). Human-owned source;\n\
         `v1.json` is the machine-readable `FormTemplate` compiled from it.\n\
         \n\
         ## Field table\n\
         \n\
         Status: `verified` = seen on the official PDF; `corroborated`\n\
         = ≥2 independent public copies agree; `TBD` = unverifiable.\n\
         \n\
         | Key | Label | Type | Required | Status | Notes |\n\
         |---|---|---|---|---|---|\n\
         \n\
         ## TBD (not in v1.json, not on the route)\n\
         \n\
         - Official PDF identity + edition mark (`authority_revision`).\n\
         - `PdfRect` coordinates (measure from an official scan).\n\
         - Submission semantics: never invent; nothing wired.\n"
    )
}

/// CLI entry: scaffold by default, `--check` compares instead.
pub fn run(args: &[String]) {
    let out = crate::flag(args, "out").unwrap_or_else(|| ".".to_string());
    let root = PathBuf::from(out);
    let authority = crate::required(args, "authority");
    let code = crate::required(args, "code");
    if args.iter().any(|a| a == "--check") {
        match check(&root, &authority, &code) {
            Ok(()) => println!("form-scaffold: generated copy matches"),
            Err(e) => {
                eprintln!("form-scaffold --check: {e}");
                std::process::exit(1);
            }
        }
        return;
    }
    let title = crate::required(args, "title");
    let force = args.iter().any(|a| a == "--force");
    match scaffold(&root, &authority, &code, &title, force) {
        Ok(paths) => {
            for path in &paths {
                println!("wrote {}", path.display());
            }
            println!("next: fill REQUIREMENTS.md, author v1.json, build the route (spec §4)");
        }
        Err(e) => {
            eprintln!("form-scaffold: {e}");
            std::process::exit(2);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_root() -> tempfile::TempDir {
        tempfile::tempdir().expect("tempdir for form-scaffold tests")
    }

    #[test]
    fn scaffold_writes_skeleton_and_matching_copy() {
        let root = temp_root();
        let paths = scaffold(root.path(), "us-dos", "ds-9999", "Demo Form", false).unwrap();
        assert_eq!(paths.len(), 3);
        for path in &paths {
            assert!(path.is_file(), "missing {}", path.display());
        }
        // v1.json is template-shaped JSON with no fields yet.
        let v1: serde_json::Value = serde_json::from_str(
            &std::fs::read_to_string(root.path().join("forms/us-dos/ds-9999/v1.json")).unwrap(),
        )
        .unwrap();
        assert_eq!(v1["status"], "draft");
        assert_eq!(v1["version"], 1);
        assert_eq!(v1["fields"].as_array().unwrap().len(), 0);
        check(root.path(), "us-dos", "ds-9999").unwrap();
    }

    #[test]
    fn scaffold_refuses_overwrite_without_force() {
        let root = temp_root();
        scaffold(root.path(), "us-dos", "ds-9999", "Demo Form", false).unwrap();
        let err = scaffold(root.path(), "us-dos", "ds-9999", "Demo Form", false).unwrap_err();
        assert!(err.contains("--force"), "unexpected: {err}");
        scaffold(root.path(), "us-dos", "ds-9999", "Demo Form", true).unwrap();
    }

    #[test]
    fn scaffold_rejects_bad_slugs_and_blank_title() {
        let root = temp_root();
        for (authority, code) in [
            ("US-DOS", "ds-9999"),
            ("us_dos", "ds-9999"),
            ("", "ds-9999"),
            ("---", "ds-9999"),
            ("us-dos", "DS-9999"),
            ("us-dos", "../escape"),
        ] {
            assert!(
                scaffold(root.path(), authority, code, "T", true).is_err(),
                "accepted {authority:?}/{code:?}"
            );
        }
        assert!(scaffold(root.path(), "us-dos", "ds-9999", "  ", true).is_err());
    }

    #[test]
    fn check_reports_field_key_drift() {
        let root = temp_root();
        scaffold(root.path(), "us-dos", "ds-9999", "Demo Form", false).unwrap();
        let v1_path = root.path().join("forms/us-dos/ds-9999/v1.json");
        let mut v1: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(&v1_path).unwrap()).unwrap();
        v1["fields"] = serde_json::json!([{ "key": "added_later" }]);
        std::fs::write(&v1_path, v1.to_string()).unwrap();
        let err = check(root.path(), "us-dos", "ds-9999").unwrap_err();
        assert!(err.contains("added_later"), "unexpected: {err}");
    }

    #[test]
    fn check_compares_latest_edition() {
        let root = temp_root();
        scaffold(root.path(), "us-dos", "ds-9999", "Demo Form", false).unwrap();
        let dir = root.path().join("forms/us-dos/ds-9999");
        std::fs::write(dir.join("v2.json"), "{\"fields\": []}").unwrap();
        // Generated copy still matches v1, so v2 drift must fail.
        assert!(check(root.path(), "us-dos", "ds-9999").is_err());
    }

    #[test]
    fn check_fails_without_editions() {
        let root = temp_root();
        let err = check(root.path(), "us-dos", "ds-9999").unwrap_err();
        assert!(err.contains("no v<n>.json"), "unexpected: {err}");
    }
}
